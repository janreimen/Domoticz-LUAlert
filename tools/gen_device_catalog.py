#!/usr/bin/env python3
"""Generate docs/DEVICES.md from the device model in lu_alert/constants.py.

    python3 tools/gen_device_catalog.py          write docs/DEVICES.md
    python3 tools/gen_device_catalog.py --check  exit 1 when docs/DEVICES.md is stale (the test suite does the same)
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from lu_alert import constants as c  # noqa: E402

TARGET = os.path.join(ROOT, "docs", "DEVICES.md")

# what each fixed device shows
MEANING = {
    "active": "the number of alerts in force after all filters (minimum severity, location, ignored categories)",
    "highest": "the colour and the text of the most severe active alert; green \"No active alerts\" when there is none",
    "critical": "On while at least one *Extreme* or *Severe* alert is active",
    "severe": "On while at least one *Severe* alert is active",
    "extreme": "On while at least one *Extreme* alert is active",
    "local": "On while the area of an active alert contains your home (needs the location filter)",
    "watchlist": "On while the text of an active alert contains one of your watchlist keywords",
    "allergen": "On while the text of an active alert contains one of your allergens",
    "status": "the connection: On while polls succeed, Off while they fail",
    "feed_info": "the state of the last poll: `OK 12:05: 12 files (1 new), 2 active`, or since when the feed is not reachable",
    "count_extreme": "the number of active *Extreme* alerts",
    "count_severe": "the number of active *Severe* alerts",
    "count_moderate": "the number of active *Moderate* alerts",
    "count_minor": "the number of active *Minor* alerts",
    "count_information": "the number of active *Information* alerts",
}

TYPES = {
    c.KIND_COUNT: "Custom Sensor",
    c.KIND_FLAG: "Switch (On/Off), read-only",
    c.KIND_TEXT: "Text, read-only",
    c.KIND_ALERT: "Alert, read-only",
}

COLOURS = {c.ALERT_GREY: "grey", c.ALERT_GREEN: "green", c.ALERT_YELLOW: "yellow", c.ALERT_ORANGE: "orange",
           c.ALERT_RED: "red"}

# the fixed devices in the order of the document: (heading, intro, units)
SECTIONS = (
    ("Summary (units %d-%d)" % (c.UNIT_ACTIVE, c.UNIT_HIGHEST),
     "The two devices to look at first: how many alerts there are and how bad the worst one is.",
     (c.UNIT_ACTIVE, c.UNIT_HIGHEST)),
    ("Switches for notifications and scripts (units %d-%d)" % (c.UNIT_CRITICAL, c.UNIT_ALLERGEN),
     "On/Off switches that only *show* a state: use them as the condition of a notification, a scene or a dzVents "
     "script. They cannot be switched by hand; a command is answered with the real state.",
     tuple(range(c.UNIT_CRITICAL, c.UNIT_ALLERGEN + 1))),
    ("Feed (units %d-%d)" % (c.UNIT_STATUS, c.UNIT_FEED_INFO),
     "Whether the plugin can read the feed. A failing feed never clears the alerts: the alert devices keep the last "
     "known alerts (they still end when their end time passes) and *Feed Info* says since when the feed is not "
     "reachable.",
     (c.UNIT_STATUS, c.UNIT_FEED_INFO)),
    ("Counters per severity (units %d-%d)" % (c.UNIT_COUNT_EXTREME, c.UNIT_COUNT_INFORMATION),
     "One counter per severity, for graphs and for rules such as \"two or more Moderate alerts\".",
     tuple(range(c.UNIT_COUNT_EXTREME, c.UNIT_COUNT_INFORMATION + 1))),
)


def _table(units):
    out = ["| Unit | Name | Type | Unit label | Shows |", "|---:|---|---|---|---|"]
    by_unit = {d.unit: d for d in c.FIXED_DEVICES}
    for unit in units:
        spec = by_unit[unit]
        out.append("| %d | %s | %s | %s | %s |" % (spec.unit, spec.name, TYPES[spec.kind], spec.label or "-",
                                                  MEANING[spec.key]))
    return out


def render():
    out = [
        "# Devices",
        "",
        "<!-- Generated by tools/gen_device_catalog.py from lu_alert/constants.py. Do not edit by hand: run the tool. -->",
        "",
        "The plugin creates the devices below. No unit number ever changes once released, so an upgrade keeps every "
        "device, its history, scenes, scripts and schedules.",
        "",
        "Every device is created when missing (at start and at every poll) and in use from the start; counters show "
        "their unit. All devices are read-only: the plugin shows what the feed says and sends nothing back.",
        "",
    ]
    for heading, intro, units in SECTIONS:
        out += ["## %s" % heading, "", intro, ""]
        out += _table(units)
        out.append("")
    out += [
        "## Alert 1 ... Alert %d (units %d-%d)" % (c.MAX_ALERT_DEVICES, c.UNIT_ALERT_FIRST, c.UNIT_ALERT_LAST),
        "",
        "One Alert device per active alert, the most severe first (of equal severity the newest first). Each shows a "
        "colour and a text such as `[Severe] Storm warning for the whole country - until 2026-11-02 14:00`. A slot "
        "without an alert is green and says *%s*." % c.TEXT_NO_ALERT,
        "",
        "Only the first %d are created (`LU_ALERT_DEVICES` in `.env`, 1-%d); the *Active Alerts* counter and the "
        "per-severity counters always count all alerts. A slot above the configured number that exists from an "
        "earlier setting turns grey and says *%s*; it is never deleted by the plugin."
        % (c.DEFAULT_ALERT_DEVICES, c.MAX_ALERT_DEVICES, c.TEXT_UNUSED),
        "",
        "| Unit | Name | Type |",
        "|---:|---|---|",
    ]
    for spec in c.ALERT_SLOTS:
        out.append("| %d | %s | %s |" % (spec.unit, spec.name, TYPES[spec.kind]))
    out += [
        "",
        "## Colours",
        "",
        "The colour of *Highest Severity* and of the *Alert n* devices follows the severity of the alert:",
        "",
        "| Severity | Colour | Domoticz alert level |",
        "|---|---|---:|",
    ]
    for severity in c.SEVERITIES:
        level = c.SEVERITY_ALERT_LEVEL[severity]
        out.append("| %s | %s | %d |" % (severity, COLOURS[level], level))
    out += [
        "",
        "The severity comes from the LU-Alert *level* of the message when it has one, otherwise from the CAP "
        "`severity` field; see [LU-ALERT-DATA.md](LU-ALERT-DATA.md) for the level table and all rules.",
        "",
        "## How the devices behave",
        "",
        "- Values are written when they change, and every %d seconds even when they did not, so Domoticz' sensor "
        "time-out never marks a quiet sensor as dead." % c.REFRESH_SECONDS,
        "- A name or a visibility you set in Domoticz is never changed by the plugin; it only writes values.",
        "- A device you delete in Domoticz is created again on the next poll.",
        "- A text is cut to %d characters, the most Domoticz can keep." % c.MAX_TEXT,
        "- Domoticz refuses new devices while *Setup > Settings > System > Accept new Hardware Devices* is off. The "
        "plugin says so once in the log and asks again every %d minutes, so the devices appear as soon as the setting "
        "is on, without restarting the hardware." % (c.CREATE_RETRY_SECONDS // 60),
        "",
    ]
    return "\n".join(out)


def main(argv):
    text = render()
    if "--check" in argv:
        try:
            with open(TARGET, encoding="utf-8") as fh:
                current = fh.read()
        except OSError:
            current = None
        if current != text:
            print("docs/DEVICES.md is stale: run python3 tools/gen_device_catalog.py", file=sys.stderr)
            return 1
        return 0
    os.makedirs(os.path.dirname(TARGET), exist_ok=True)
    with open(TARGET, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote", os.path.relpath(TARGET, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
